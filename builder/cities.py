def suggest_cities(db) -> list[str]:
    candidates = {x.strip() for x in CITIES if x.strip()}
    for record in db.routes(include_archived=True):
        for key in ("origin", "destination"):
            name = str(record.get(key) or "").strip()
            if name:
                candidates.add(name)
    # Не возвращаем одинаковые варианты с разным регистром.
    by_name = {}
    for city in sorted(candidates, key=str.casefold):
        by_name.setdefault(city.casefold().replace("ё", "е"), city)
    return list(by_name.values())


def setup_city_completers(route_dialog, db):
    cities = suggest_cities(db)
    for key in ("origin", "destination"):
        widget = route_dialog.fields.get(key)
        if widget is None:
            continue
        completer = QCompleter(cities, widget)
        completer.setCaseSensitivity(Qt.CaseSensitivity.CaseInsensitive)
        completer.setFilterMode(Qt.MatchFlag.MatchStartsWith)
        completer.setCompletionMode(QCompleter.CompletionMode.PopupCompletion)
        completer.setMaxVisibleItems(12)
        widget.setCompleter(completer)
        make_popup_readable(completer, widget)
